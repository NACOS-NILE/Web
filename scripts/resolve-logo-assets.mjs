/**
 * Some logos in public/logos/ get swapped out by hand (different source,
 * different file format) without touching any component code. This script
 * finds whichever extension is actually on disk for each swappable logo and
 * writes it to src/lib/logo-assets.generated.ts, which components import
 * from instead of hardcoding a path with a specific extension.
 *
 * Runs automatically before `next dev` / `next build` (see package.json).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const LOGOS_DIR = path.join(__dirname, "..", "public", "logos");
const OUTPUT_FILE = path.join(__dirname, "..", "src", "lib", "logo-assets.generated.ts");

// Preference order when more than one matching file exists for the same base name.
const EXTENSION_PRIORITY = ["png", "svg", "webp", "jpg", "jpeg", "avif", "gif"];

// Logical name -> base filename (without extension) to resolve in public/logos/.
const SWAPPABLE_LOGOS = [{ constName: "NACOS_LOGO_SRC", base: "nacos" }];

function resolveExtension(base) {
  const matches = fs
    .readdirSync(LOGOS_DIR)
    .filter((file) => path.parse(file).name === base && path.extname(file).length > 1);

  if (matches.length === 0) {
    throw new Error(
      `resolve-logo-assets: no file named "${base}.*" found in ${LOGOS_DIR}. ` +
        `Add one (any image extension) and rerun.`,
    );
  }

  if (matches.length === 1) return matches[0];

  const sorted = [...matches].sort((a, b) => {
    const ai = EXTENSION_PRIORITY.indexOf(path.extname(a).slice(1).toLowerCase());
    const bi = EXTENSION_PRIORITY.indexOf(path.extname(b).slice(1).toLowerCase());
    return (ai === -1 ? Infinity : ai) - (bi === -1 ? Infinity : bi);
  });

  console.warn(
    `resolve-logo-assets: multiple files match "${base}.*" (${matches.join(", ")}). ` +
      `Using "${sorted[0]}" — remove the others to silence this warning.`,
  );

  return sorted[0];
}

const lines = [
  "// Auto-generated by scripts/resolve-logo-assets.mjs — do not edit by hand.",
  "// Regenerated automatically before `next dev` and `next build`.",
  "",
];

for (const { constName, base } of SWAPPABLE_LOGOS) {
  const file = resolveExtension(base);
  lines.push(`export const ${constName} = "/logos/${file}";`);
}

fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
fs.writeFileSync(OUTPUT_FILE, lines.join("\n") + "\n");
console.log(`resolve-logo-assets: wrote ${path.relative(process.cwd(), OUTPUT_FILE)}`);
